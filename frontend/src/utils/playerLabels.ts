export function formatTmPositionRu(tmPosition?: string | null, gamePosition?: string): string {
  const raw = (tmPosition || '').trim()
  if (raw) {
    const exact = TM_POSITION_RU[raw]
    if (exact) return exact
    const lower = raw.toLowerCase()
    for (const [en, ru] of Object.entries(TM_POSITION_RU)) {
      if (en.toLowerCase() === lower) return ru
    }
    return raw
  }
  const gp = (gamePosition || '').trim()
  return GAME_POSITION_RU[gp] ?? gp
}

export function formatCountryNameRu(name?: string | null): string {
  const raw = (name || '').trim()
  if (!raw) return ''
  const exact = COUNTRY_NAME_RU[raw]
  if (exact) return exact
  const lower = raw.toLowerCase()
  for (const [en, ru] of Object.entries(COUNTRY_NAME_RU)) {
    if (en.toLowerCase() === lower) return ru
  }
  return raw
}
